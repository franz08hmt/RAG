from __future__ import annotations

import time
import hashlib
import json
import os
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

import numpy as np

from rag_hcmute.ingestion.chunk import Chunk
from rag_hcmute.retrieval.common import RetrievalHit, hit_from_chunk, load_chunks

DEFAULT_MODEL_NAME = "BAAI/bge-m3"
NORMALIZATION = "l2_normalize_embeddings_cosine_via_inner_product"
MAX_SEQ_LENGTH = 1024


def embedding_cache_key(chunks: list[Chunk], model_path: Path) -> str:
    """Content fingerprint: model files, ordered chunks and encoding contract.

    Hash model contents rather than path timestamps so a replaced local weight
    file cannot silently reuse embeddings generated by another model.
    """
    if not model_path.is_dir():
        raise ValueError("Embedding cache requires an existing local model directory.")
    digest = hashlib.sha256()
    digest.update(f"dense-cache-v1|{MAX_SEQ_LENGTH}|{NORMALIZATION}|float32".encode())
    for file in sorted(path for path in model_path.rglob("*") if path.is_file()):
        digest.update(file.relative_to(model_path).as_posix().encode())
        with file.open("rb") as stream:
            while block := stream.read(8 * 1024 * 1024):
                digest.update(block)
    for chunk in chunks:
        digest.update(json.dumps([chunk.chunk_id, chunk.text], ensure_ascii=False).encode("utf-8"))
    return digest.hexdigest()


def _load_cached_embeddings(path: Path, *, key: str, count: int) -> np.ndarray | None:
    try:
        with np.load(path, allow_pickle=False) as cached:
            values = cached["embeddings"]
            if str(cached["key"]) != key or values.dtype != np.float32:
                return None
            if values.ndim != 2 or values.shape[0] != count or values.shape[1] < 1:
                return None
            if not np.isfinite(values).all():
                return None
            if not np.allclose(np.linalg.norm(values, axis=1), 1.0, atol=1e-4):
                return None
            if str(cached["sha256"]) != hashlib.sha256(values.tobytes()).hexdigest():
                return None
            return values.copy()
    except (OSError, ValueError, KeyError, EOFError):
        return None


def _save_cached_embeddings(path: Path, key: str, values: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, suffix=".npz", delete=False) as stream:
        temporary = Path(stream.name)
        np.savez_compressed(stream, key=key, embeddings=values,
                            sha256=hashlib.sha256(values.tobytes()).hexdigest())
    os.replace(temporary, path)


class DenseRetrievalUnavailable(RuntimeError):
    """Raised when the dense pipeline cannot run in this environment (deps/model/resources)."""


@dataclass
class DenseQueryResult:
    hits: list[RetrievalHit]
    latency_ms: float


class DenseRetriever:
    method_name = "dense_bge_m3"

    def __init__(self, chunks: list[Chunk], model_name: str = DEFAULT_MODEL_NAME, *,
                 batch_size: int = 32, cache_dir: Path | None = None,
                 progress: Callable[[str], None] | None = None):
        if not chunks:
            raise ValueError("Khong the xay dung dense index tu danh sach chunk rong.")
        self.chunks = chunks
        self.model_name = model_name
        if batch_size < 1:
            raise ValueError("Embedding batch_size must be positive.")
        self.batch_size = batch_size
        self.startup_metrics = {"cache_hit": False, "batch_size": batch_size}
        emit = progress or (lambda _message: None)
        started = time.perf_counter()
        emit("Dense: importing inference libraries...")

        try:
            import faiss  # noqa: F401
            from sentence_transformers import SentenceTransformer
        except ImportError as exc:
            raise DenseRetrievalUnavailable(
                f"Thieu thu vien can thiet cho dense retrieval: {exc}. "
                "Can 'pip install sentence-transformers faiss-cpu'."
            ) from exc

        self.startup_metrics["library_import_seconds"] = time.perf_counter() - started
        try:
            started = time.perf_counter()
            emit("Dense: loading local embedding model...")
            self._model = SentenceTransformer(model_name)
            # BGE-M3 defaults to max_seq_length=8192 for long-document support; our chunks are
            # capped by whitespace tokens, which are not model tokens. The 1024 model-token
            # cap is the current experimental contract; truncation is audited separately.
            self._model.max_seq_length = MAX_SEQ_LENGTH
            self.startup_metrics["model_load_seconds"] = time.perf_counter() - started
            self.startup_metrics["device"] = str(self._model.device)
        except Exception as exc:
            raise DenseRetrievalUnavailable(
                f"Khong tai duoc model '{model_name}' (co the do moi truong khong co quyen "
                f"truy cap huggingface.co hoac khong du tai nguyen): {exc}"
            ) from exc

        import faiss

        embeddings = None
        cache_path = None
        started = time.perf_counter()
        if cache_dir is not None:
            emit("Dense: checking model/chunk content fingerprint and local cache...")
            key = embedding_cache_key(chunks, Path(model_name))
            cache_path = cache_dir / f"{key}.npz"
            embeddings = _load_cached_embeddings(cache_path, key=key, count=len(chunks))
            self.startup_metrics["cache_key"] = key
            self.startup_metrics["cache_hit"] = embeddings is not None
        self.startup_metrics["cache_check_seconds"] = time.perf_counter() - started
        try:
            started = time.perf_counter()
            if embeddings is None:
                emit(f"Dense: encoding {len(chunks)} chunks, batch_size={batch_size}...")
                embeddings = self._encode([c.text for c in chunks])
                if cache_path is not None:
                    _save_cached_embeddings(cache_path, key, embeddings)
            else:
                emit(f"Dense: reusing cached embeddings for {len(chunks)} chunks.")
            self.startup_metrics["corpus_encode_and_cache_write_seconds"] = time.perf_counter() - started
        except Exception as exc:
            raise DenseRetrievalUnavailable(f"Loi khi sinh embedding cho corpus: {exc}") from exc

        started = time.perf_counter()
        self._dim = embeddings.shape[1]
        self._index = faiss.IndexFlatIP(self._dim)
        self._index.add(embeddings)
        self.startup_metrics["index_build_seconds"] = time.perf_counter() - started

    def _encode(self, texts: list[str]) -> np.ndarray:
        embeddings = self._model.encode(
            texts,
            normalize_embeddings=True,
            show_progress_bar=False,
            convert_to_numpy=True,
            batch_size=self.batch_size,
        )
        return np.asarray(embeddings, dtype="float32")

    @classmethod
    def from_snapshot(cls, chunks_path: Path, model_name: str = DEFAULT_MODEL_NAME) -> "DenseRetriever":
        return cls(load_chunks(chunks_path), model_name=model_name)

    def query(self, query_text: str, top_k: int = 5) -> DenseQueryResult:
        start = time.perf_counter()
        query_embedding = self._encode([query_text])
        scores, indices = self._index.search(query_embedding, top_k)
        hits = [
            hit_from_chunk(rank + 1, self.chunks[idx], float(score))
            for rank, (idx, score) in enumerate(zip(indices[0], scores[0]))
            if idx != -1
        ]
        latency_ms = (time.perf_counter() - start) * 1000
        return DenseQueryResult(hits=hits, latency_ms=latency_ms)
